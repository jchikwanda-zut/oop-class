public class Proceedural {
    public static void main(String[] args) {
        // Data
        String[] names = {"Ben", "Mary", "Op", "Ben"};
        int[] ages = {10, 6, 2};
        
        // Logic or the instructions
        for (int i = 0; i < names.length; i++) {
            System.out.println(names[i] + " is " + ages[i] + " years old");
        }
    }
}
